    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        String sql = "select tipo Tipo from empleados where usuario = ? and contrasena = ?";

        try (Connection conexion = Conexion.conectar();
            PreparedStatement statement = conexion.prepareStatement(sql)) {

            statement.setString(1, txtUsuario.getText());
            statement.setString(2, pfContrasena.getText());

            ResultSet resultado = statement.executeQuery();

            if (resultado.next()) {
                int tipoUsuario = resultado.getInt("Tipo");
                System.out.println("login correcto");
                frmPrincipal form = new frmPrincipal(tipoUsuario);
                this.dispose();
                form.setVisible(true);
            } else {
                lbError.setText("usuario o contraseña incorrectos");
            }

        } catch (Exception e) {
            System.out.println("error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

