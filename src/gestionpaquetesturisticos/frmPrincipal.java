    private void mostrarTipoDeUsuario() { 
        switch (tipoEmpleado) {
            case 1:
                lbTipoUsuario.setText("Usuario es: ADMINISTRADOR");
                break;
            case 2:
                lbTipoUsuario.setText("Usuario es: EMPLEADO");
                break;
            default:
                lbTipoUsuario.setText("Usuario es: ERROR");
                lbTipoUsuario.setForeground(Color.red);
                break;
        }
    }      
    
